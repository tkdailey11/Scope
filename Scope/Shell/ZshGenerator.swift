//
//  ZshGenerator.swift
//  Scope
//
//  Deterministic generated.zsh output. No timestamps, stable ordering,
//  so golden-file tests are possible.
//

import Foundation

nonisolated enum ZshGenerator {
    static let header = "# Generated by Scope. Manual edits may be overwritten."

    /// Throws if any value cannot be safely quoted. Callers should surface
    /// `EffectiveConfiguration.issues` first; errors here are a last line of defense.
    static func generate(_ config: EffectiveConfiguration) throws -> String {
        var sections: [String] = [header]

        let env = try config.environment.compactMap { try exportLine(for: $0.item) }
        if !env.isEmpty { sections.append(block("Environment", env)) }

        // `config.path` is highest priority first. Each line prepends, so emit in
        // reverse: the last line written (highest priority) ends up first in $PATH.
        let path = try config.path.reversed().map {
            "export PATH=\"\(try ZshQuoting.pathComponent($0.rawPath).dropFirstAndLast()):$PATH\""
        }
        if !path.isEmpty { sections.append(block("PATH", path)) }

        let aliases = try config.aliases.map {
            "alias \($0.item.name)=\(try ZshQuoting.literal($0.item.command))"
        }
        if !aliases.isEmpty { sections.append(block("Aliases", aliases)) }

        let functions = config.functions.map { resolved -> String in
            let body = resolved.item.body.trimmingCharacters(in: .newlines)
            return "\(resolved.item.name)() {\n\(body)\n}"
        }
        if !functions.isEmpty {
            sections.append("# Functions\n" + functions.joined(separator: "\n\n"))
        }

        return sections.joined(separator: "\n\n") + "\n"
    }

    /// The `export` line for one variable, or nil if it has no plaintext value to write
    /// (secret-backed or empty). Also used by the editor to preview exactly what will be generated.
    static func exportLine(for variable: EnvironmentVariable) throws -> String? {
        guard variable.secretReference == nil, let value = variable.value else { return nil }
        let quoted = switch variable.valueMode {
        case .literal: try ZshQuoting.literal(value)
        case .expression: try ZshQuoting.expression(value)
        }
        return "export \(variable.name)=\(quoted)"
    }

    private static func block(_ title: String, _ lines: [String]) -> String {
        "# \(title)\n" + lines.joined(separator: "\n")
    }
}

private extension String {
    /// Strips the surrounding quote characters added by `ZshQuoting.expression`.
    nonisolated func dropFirstAndLast() -> String { String(dropFirst().dropLast()) }
}
