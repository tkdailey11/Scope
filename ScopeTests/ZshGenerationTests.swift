import Foundation
import Testing
@testable import Scope

struct ZshQuotingTests {
    @Test func literalQuoting() throws {
        #expect(try ZshQuoting.literal("plain") == "'plain'")
        #expect(try ZshQuoting.literal("a b") == "'a b'")
        #expect(try ZshQuoting.literal("it's") == "'it'\\''s'")
        #expect(try ZshQuoting.literal("$HOME `x` $(y) \\n") == "'$HOME `x` $(y) \\n'")
        #expect(try ZshQuoting.literal("a\nb") == "'a\nb'")
    }

    @Test func expressionKeepsExpansionsButEscapesBareQuotes() throws {
        #expect(try ZshQuoting.expression("$HOME/go") == "\"$HOME/go\"")
        #expect(try ZshQuoting.expression("say \"hi\"") == "\"say \\\"hi\\\"\"")
        #expect(try ZshQuoting.expression("already \\\" escaped") == "\"already \\\" escaped\"")
    }

    @Test func expressionRejectsDanglingBackslash() {
        #expect(throws: ZshQuotingError.danglingBackslash) { try ZshQuoting.expression("oops\\") }
    }

    @Test func nulIsRejected() {
        #expect(throws: ZshQuotingError.containsNUL) { try ZshQuoting.literal("a\0b") }
    }

    @Test func pathTildeBecomesHome() throws {
        #expect(try ZshQuoting.pathComponent("~/go/bin") == "\"$HOME/go/bin\"")
        #expect(try ZshQuoting.pathComponent("~") == "\"$HOME\"")
        #expect(try ZshQuoting.pathComponent("/opt/my dir") == "\"/opt/my dir\"")
    }

    @Test func nameValidation() {
        #expect(ZshSyntax.isValidVariableName("GOPATH"))
        #expect(!ZshSyntax.isValidVariableName("1A"))
        #expect(!ZshSyntax.isValidVariableName("A-B"))
        #expect(ZshSyntax.isValidAliasName("gs"))
        #expect(ZshSyntax.isValidAliasName("..."))
        #expect(!ZshSyntax.isValidAliasName("a b"))
        #expect(!ZshSyntax.isValidAliasName("a=b"))
        #expect(ZshSyntax.isValidFunctionName("mkcd"))
        #expect(!ZshSyntax.isValidFunctionName("9x"))
    }
}

struct ZshGeneratorTests {
    private var sample: EffectiveConfiguration {
        ConfigurationComposer.compose(
            ConfigurationSnapshot(
                environment: [
                    .init(name: "GOPATH", value: "$HOME/go", valueMode: .expression),
                    .init(name: "EDITOR", value: "nvim"),
                ],
                path: [
                    .init(rawPath: "/opt/homebrew/bin", order: 0),
                    .init(rawPath: "~/go/bin", order: 1),
                ],
                aliases: [
                    .init(name: "ll", command: "ls -lah"),
                    .init(name: "gs", command: "git status"),
                ],
                functions: [.init(name: "mkcd", body: "  mkdir -p \"$1\" && cd \"$1\"\n")]
            ),
            activeProfileID: nil, machineID: nil
        )
    }

    @Test func goldenOutput() throws {
        let expected = """
        # Generated by Scope. Manual edits may be overwritten.

        # Environment
        export EDITOR='nvim'
        export GOPATH="$HOME/go"

        # PATH
        export PATH="$HOME/go/bin:$PATH"
        export PATH="/opt/homebrew/bin:$PATH"

        # Aliases
        alias gs='git status'
        alias ll='ls -lah'

        # Functions
        mkcd() {
          mkdir -p "$1" && cd "$1"
        }

        """
        #expect(try ZshGenerator.generate(sample) == expected)
    }

    @Test func outputIsDeterministic() throws {
        #expect(try ZshGenerator.generate(sample) == ZshGenerator.generate(sample))
    }

    @Test func emptyConfigurationIsJustTheHeader() throws {
        #expect(try ZshGenerator.generate(EffectiveConfiguration()) == ZshGenerator.header + "\n")
    }

    @Test func secretBackedVariablesAreNotEmitted() throws {
        let config = ConfigurationComposer.compose(
            ConfigurationSnapshot(environment: [.init(name: "TOKEN", value: "plaintext", secretReference: "kc:1")]),
            activeProfileID: nil, machineID: nil
        )
        #expect(!(try ZshGenerator.generate(config)).contains("plaintext"))
    }

    /// Round-trips tricky values through a real zsh to prove the quoting is correct.
    @Test func zshReadsBackExactLiteralValues() throws {
        let tricky = ["a b", "it's", "$HOME", "`id`", "$(id)", "back\\slash", "q\"uote", "multi\nline", "semi; echo pwned"]
        for value in tricky {
            let script = "export V=\(try ZshQuoting.literal(value))\nprintf %s \"$V\"\n"
            let process = Process()
            process.executableURL = URL(filePath: "/bin/zsh")
            process.arguments = ["-f", "-c", script]
            let pipe = Pipe()
            process.standardOutput = pipe
            try process.run()
            let data = pipe.fileHandleForReading.readDataToEndOfFile()
            process.waitUntilExit()
            #expect(String(decoding: data, as: UTF8.self) == value, "value: \(value)")
        }
    }
}
